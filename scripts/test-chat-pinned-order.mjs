import fs from 'node:fs';
import assert from 'node:assert/strict';
const source = fs.readFileSync('public/js/chat.js', 'utf8');
const start = source.indexOf('    async function loadConversations() {');
const end = source.indexOf('    // Function to load a specific conversation', start);
const rows = [];
const list = { set innerHTML(value) { rows.length = 0; }, appendChild(row) { rows.push(row); } };
let data = [{ id:'new', pinned:false }, { id:'pin-new', pinned:true }, { id:'older', pinned:false }, { id:'pin-old', pinned:true }];
const run = new Function('fetch', 'extractProjectIdFromPath', 'conversationList', 'createCompactConversationItem', 'currentConversationId', 'loadConversation', 'deleteConversation', source.slice(start, end) + '\nreturn loadConversations();');
const load = () => run(async () => ({ json:async () => data }), () => 'project', list, c => ({ id:c.id, active:false, classList:{ add() {} }, addEventListener() {}, querySelector() { return null; } }), 'older', () => {}, () => {});
await load();
assert.deepEqual(rows.map(r => r.id), ['pin-new','pin-old','new','older']);
data[0].pinned = true;
await load();
assert.deepEqual(rows.map(r => r.id), ['new','pin-new','pin-old','older']);
data[1].pinned = false;
await load();
assert.deepEqual(rows.map(r => r.id), ['new','pin-old','pin-new','older']);
console.log('PASS chat renderer keeps pinned chats first after loading, pinning, and unpinning');
