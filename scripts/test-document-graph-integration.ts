import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
const dir=mkdtempSync(join(tmpdir(),'document-graph-test-'));
process.env.DATABASE_DRIVER='sqlite';process.env.DATABASE_URL=join(dir,'test.db');
process.env.BETTER_AUTH_SECRET='document-graph-test-secret';process.env.BETTER_AUTH_URL='http://localhost:3000';
try {
  const setup=spawnSync('bunx',['drizzle-kit','push','--dialect','sqlite','--schema','./src/db/schema/sqlite/index.ts','--url',process.env.DATABASE_URL,'--force'],{encoding:'utf8',env:process.env});
  assert.equal(setup.status,0,setup.stderr);
  const {db}=await import('../src/config/db.ts');
  const {users}=await import('../src/db/schema/users.ts');
  const {projects}=await import('../src/db/schema/projects.ts');
  const {conversations,chatFiles}=await import('../src/db/schema/chat.ts');
  const {projectFiles}=await import('../src/db/schema/documents.ts');
  const {epics}=await import('../src/db/schema/epics.ts');
  const {projectTickets}=await import('../src/db/schema/tickets.ts');
  const {documentGraphSources,documentGraphs,documentGraphLinks}=await import('../src/db/schema/document-graph.ts');
  const {collectGraph,readDocumentGraph,graphId,runDocumentGraphs}=await import('../src/services/document-graph.ts');
  const {eq}=await import('drizzle-orm');
  await db.insert(users).values([{id:'alice',name:'Alice',email:'alice@example.test'},{id:'bob',name:'Bob',email:'bob@example.test'}]);
  const [project]=await db.insert(projects).values({id:'project',projectId:'public-project',name:'Project',ownerId:'alice'}).returning();
  await db.insert(projects).values({id:'foreign',projectId:'foreign-project',name:'Foreign',ownerId:'bob'});
  await db.insert(projectFiles).values([{id:'doc',projectId:'project',name:'Requirements',fileType:'prd',content:'payments'},{id:'foreign-doc',projectId:'foreign',name:'Secret',fileType:'prd',content:'secret'}]);
  await db.insert(epics).values({id:'epic',projectId:'project',name:'Payments',goal:'payment checkout'});
  await db.insert(projectTickets).values({id:'ticket',projectId:'project',name:'Build payment',description:'payment',epicId:'epic',sourceDocumentId:'doc'});
  await db.insert(conversations).values([{id:'a-chat',projectId:'public-project',userId:'alice'},{id:'b-chat',projectId:'public-project',userId:'bob'}]);
  await db.insert(chatFiles).values([{id:'a-file',conversationId:'a-chat',originalFilename:'Alice.txt',filePath:'missing'},{id:'b-file',conversationId:'b-chat',originalFilename:'Bob.txt',filePath:'missing'}]);
  await db.insert(documentGraphSources).values([{id:'a-source',projectId:'project',userId:'alice',name:'Alice source',provider:'NOTION',content:'private alice'},{id:'b-source',projectId:'project',userId:'bob',name:'Bob source',provider:'NOTION',content:'private bob'}]);
  const collected=await collectGraph(project!,'alice');
  const ids=collected.nodes.map(n=>n.id);
  assert(ids.includes('upload:a-file'));assert(ids.includes('external:a-source'));
  assert(!ids.includes('upload:b-file'));assert(!ids.includes('external:b-source'));assert(!ids.includes('document:foreign-doc'));
  assert(collected.edges.some(e=>e.source==='document:doc'&&e.target==='ticket:ticket'));
  const initial=await readDocumentGraph(project!,'alice');
  assert(initial.nodes.every(n=>!('text' in n)),'API must not expose document bodies');
  const edge={source:'document:doc',target:'epic:epic',relation:'relevant_to' as const,origin:'suggested' as const,reason:'payments',confidence:.9};
  await db.update(documentGraphs).set({snapshot:{hashes:Object.fromEntries(collected.nodes.map(n=>[n.id,n.hash])),edges:[edge]},status:'ready'}).where(eq(documentGraphs.id,graphId('project','alice')));
  assert((await readDocumentGraph(project!,'alice')).edges.some(e=>e.origin==='suggested'));
  await db.insert(documentGraphLinks).values({id:'decision',projectId:'project',userId:'alice',source:edge.source,target:edge.target,relation:edge.relation,decision:'rejected'});
  assert(!(await readDocumentGraph(project!,'alice')).edges.some(e=>e.origin==='suggested'),'dismissal survives reads');
  await db.update(documentGraphLinks).set({decision:'accepted'}).where(eq(documentGraphLinks.id,'decision'));
  assert((await readDocumentGraph(project!,'alice')).edges.some(e=>e.origin==='manual'));
  assert(!(await readDocumentGraph(project!,'bob')).edges.some(e=>e.origin==='manual'),'private decisions cannot cross users');
  await db.delete(documentGraphLinks).where(eq(documentGraphLinks.id,'decision'));
  await db.update(projectFiles).set({content:'changed requirements'}).where(eq(projectFiles.id,'doc'));
  assert(!(await readDocumentGraph(project!,'alice')).edges.some(e=>e.origin==='suggested'),'stale suggestions disappear immediately');
  await db.delete(projectFiles).where(eq(projectFiles.id,'doc'));
  assert(!(await readDocumentGraph(project!,'alice')).edges.some(e=>e.source==='document:doc'),'deleted nodes cannot leave dangling edges');
  let calls=0;
  const classify=async()=>{calls++;return [];};
  await db.update(documentGraphs).set({checkedAt:0}).where(eq(documentGraphs.id,graphId('project','alice')));
  await runDocumentGraphs(classify);
  assert(calls>0,'background worker processes new sources');
  const completed=calls;
  await db.update(documentGraphs).set({checkedAt:0}).where(eq(documentGraphs.id,graphId('project','alice')));
  await runDocumentGraphs(classify);
  assert.equal(calls,completed,'unchanged documents do not trigger paid analysis');
  await db.update(documentGraphSources).set({content:'new external content'}).where(eq(documentGraphSources.id,'a-source'));
  await db.update(documentGraphs).set({checkedAt:0}).where(eq(documentGraphs.id,graphId('project','alice')));
  await runDocumentGraphs(async()=>{throw Error('provider unavailable');});
  let state=(await db.select().from(documentGraphs).where(eq(documentGraphs.id,graphId('project','alice'))))[0]!;
  assert.equal(state.status,'error');
  await db.update(documentGraphs).set({checkedAt:0,status:'indexing'}).where(eq(documentGraphs.id,state.id));
  await runDocumentGraphs(classify);
  state=(await db.select().from(documentGraphs).where(eq(documentGraphs.id,state.id)))[0]!;
  assert.equal(state.status,'ready','expired lease recovers after restart');
  console.log('Document graph integration: private sources, explicit links, durable decisions, stale-content invalidation, and deletion checks passed.');
} finally { rmSync(dir,{recursive:true,force:true}); }
