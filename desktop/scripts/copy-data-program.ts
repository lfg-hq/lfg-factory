// Regenerates desktop/src/preview-data-program.ts from the server's program.
// Run from the repository root: bun desktop/scripts/copy-data-program.ts
import { writeFileSync } from "node:fs";
import { previewDataProgram } from "../../src/services/preview-data-program.ts";

const out = new URL("../src/preview-data-program.ts", import.meta.url);
writeFileSync(out, `// GENERATED by desktop/scripts/copy-data-program.ts from src/services/preview-data-program.ts. Do not edit.
// The fixed program behind preview data operations (accounts, test data). The server
// sends only its input, as data; this computer runs its own copy of the program.
export const PREVIEW_DATA_PROGRAM: string = ${JSON.stringify(previewDataProgram())};
`);
console.log(`Wrote ${out.pathname}`);
